    }

    public static function incluirValorAtual(array $opcoes, string $valor): array {
        if ($valor !== '' && !in_array($valor, $opcoes, true)) {
            $opcoes[] = $valor;
            sort($opcoes, SORT_NATURAL | SORT_FLAG_CASE);
        }
        return $opcoes;
    }
